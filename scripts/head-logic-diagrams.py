#!/usr/bin/env python3
"""Render current and archived Mermaid sources; index every source in the review page."""

import argparse
import json
import os
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
NOTES = ROOT / "docs/head-logic-diagrams.json"
PAGE = ROOT / "docs/head-logic-diagrams.md"
ARCHIVE = ROOT / "docs/prior-spike/diagrams.md"


def relative(path, page):
    return os.path.relpath(ROOT / path, page.parent)


def anchor(title):
    return re.sub(r"[^\w\s-]", "", title.lower()).replace(" ", "-")


def diagram_groups(notes, page):
    lines = []
    for group in dict.fromkeys(note["group"] for note in notes.values()):
        lines.extend([f"## {group}", ""])
        for path, note in notes.items():
            if note["group"] != group:
                continue
            lines.extend(
                [
                    f"### {note['title']}",
                    "",
                    note["description"],
                    "",
                    f"[Mermaid source]({relative(path, page)})",
                    "",
                    "```mermaid",
                    (ROOT / path).read_text().rstrip(),
                    "```",
                    "",
                ]
            )
    return lines


def render():
    files = set(
        subprocess.check_output(
            ["rg", "--files", "-g", "*.mmd"], cwd=ROOT, text=True
        ).splitlines()
    )
    notes = json.loads(NOTES.read_text())
    missing = files - notes.keys()
    obsolete = notes.keys() - files
    if missing or obsolete:
        raise SystemExit(
            f"Diagram notes missing: {sorted(missing)}\nSources missing: {sorted(obsolete)}"
        )
    for path, note in notes.items():
        if not note["description"].strip():
            raise SystemExit(f"Empty diagram explanation: {path}")
    current = {path: note for path, note in notes.items() if not path.startswith("docs/prior-spike/")}
    archived = {path: note for path, note in notes.items() if path.startswith("docs/prior-spike/")}
    lines = [
        "# Head logic diagrams",
        "",
        "Current Crem/Program diagrams are rendered below. Every `.mmd` in the checkout",
        "has a source link and explanation here; archived diagrams have a separate index",
        "at the end. Phase graphs describe permitted transitions; sequence",
        "diagrams describe one execution, with lanes for head logic, ledger,",
        "cryptography, staged changes and buffered effects. Arrows preserve instruction",
        "order; a staged change is retained only if the terminal result allows it.",
        "",
        "Start with [Complete snapshot round](#complete-snapshot-round),",
        "[Decommit dependencies and reservation](#decommit-dependencies-and-reservation),",
        "or [Capacity pruning and progress](#capacity-pruning-and-progress).",
        "",
        "[Design](head-logic-review.md) · [Tracing commands](head-logic/tools.md)",
        "",
        "Generated by `python3 scripts/head-logic-diagrams.py` from the sources and",
        "`docs/head-logic-diagrams.json`. `--check` verifies coverage and freshness.",
        "",
    ]
    lines.extend(diagram_groups(current, PAGE))
    lines.extend(
        [
            "## Archived diagrams",
            "",
            "<details>",
            f"<summary>Prior-spike index ({len(archived)} diagrams)</summary>",
            "",
            "These records are rendered in [prior-spike/diagrams.md](prior-spike/diagrams.md).",
            "They include superseded behavior, deliberate mutations, and migration comparisons.",
            "",
            "| Diagram | What it records | Source |",
            "| --- | --- | --- |",
        ]
    )
    for path, note in archived.items():
        description = note["description"].replace("|", r"\|")
        lines.append(
            f"| [{note['title']}](prior-spike/diagrams.md#{anchor(note['title'])})"
            f" | {description} | [Mermaid]({relative(path, PAGE)}) |"
        )
    lines.extend(["", "</details>", ""])
    archive_lines = [
        "# Prior-spike diagrams",
        "",
        "Archived from `a6c4966f8`. These are protocol investigations, superseded traces,",
        "and comparisons with frozen implementations. They describe the versions",
        "named by their artifacts, not a second production execution path.",
        "",
        "[Current diagrams](../head-logic-diagrams.md) · [Archive guide](README.md)",
        "",
        "Generated by `python3 scripts/head-logic-diagrams.py`; `--check` verifies both pages.",
        "",
    ]
    archive_lines.extend(diagram_groups(archived, ARCHIVE))
    return {PAGE: "\n".join(lines), ARCHIVE: "\n".join(archive_lines)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if coverage or the page is stale")
    args = parser.parse_args()
    for page, content in render().items():
        if args.check:
            if not page.exists() or page.read_text() != content:
                raise SystemExit(f"Diagram page is stale: {page.relative_to(ROOT)}; run python3 scripts/head-logic-diagrams.py")
        else:
            page.write_text(content)
    print(f"{len(json.loads(NOTES.read_text()))} diagrams covered")


if __name__ == "__main__":
    main()
