#!/usr/bin/env python3
"""Render every checked-in Mermaid source in one review page; reject missing notes."""

import argparse
import json
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
NOTES = ROOT / "docs/head-logic-diagrams.json"
PAGE = ROOT / "docs/head-logic-diagrams.md"


def render():
    files = set(
        subprocess.check_output(
            ["rg", "--files", "-g", "*.mmd"], cwd=ROOT, text=True
        ).splitlines()
    )
    notes = json.loads(NOTES.read_text())
    missing = files - notes.keys()
    obsolete = notes.keys() - files
    if missing or obsolete:
        raise SystemExit(
            f"Diagram notes missing: {sorted(missing)}\nSources missing: {sorted(obsolete)}"
        )
    lines = [
        "# Head logic diagrams",
        "",
        "Every `.mmd` file in this checkout is rendered below. The source links open",
        "the standalone files. Phase graphs describe permitted transitions; sequence",
        "diagrams describe one execution, with lanes for head logic, ledger,",
        "cryptography, staged changes and buffered effects. Arrows preserve instruction",
        "order; a staged change is retained only if the terminal result allows it.",
        "",
        "Start with [Decommit dependency failure](#decommit-dependency-failure) for a real protocol bug, or",
        "[Invalid final acknowledgement](#invalid-final-acknowledgement) for staging followed by rejection.",
        "Historical v1 artifacts are labelled; use the v2 scenarios for replay.",
        "",
        "[Design](head-logic-review.md) · [Experiments](docs/dev/architecture/head-logic-experiments/README.md)",
        "",
        "Generated by `python3 scripts/head-logic-diagrams.py` from the sources and",
        "`docs/head-logic-diagrams.json`. `--check` verifies coverage and freshness.",
        "",
    ]
    for group in dict.fromkeys(note["group"] for note in notes.values()):
        lines.extend([f"## {group}", ""])
        if group == "Workflow comparisons":
            lines.extend(
                [
                    "ReqTx, ReqSn and AckSn traces show both frozen free-program and crem execution.",
                    "ReqDec and Recover show production execution checked against frozen outcomes.",
                    "",
                ]
            )
        members = [(path, note) for path, note in notes.items() if note["group"] == group]
        for path, note in members:
            if not note["description"].strip():
                raise SystemExit(f"Empty diagram explanation: {path}")
            relative = os.path.relpath(ROOT / path, PAGE.parent)
            lines.extend(
                [
                    f"### {note['title']}",
                    "",
                    note["description"],
                    "",
                    f"[Mermaid source]({relative})",
                    "",
                    "```mermaid",
                    (ROOT / path).read_text().rstrip(),
                    "```",
                    "",
                ]
            )
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if coverage or the page is stale")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not PAGE.exists() or PAGE.read_text() != content:
            raise SystemExit("Diagram page is stale; run python3 scripts/head-logic-diagrams.py")
    else:
        PAGE.write_text(content)
    print(f"{len(json.loads(NOTES.read_text()))} diagrams covered")


if __name__ == "__main__":
    main()
